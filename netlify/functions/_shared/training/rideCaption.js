// The cycling caption. The shared lines — fitness, fatigue and form from the
// ride-only series, and load against typical — read exactly as a run's do.
// Below them, what a bike computer has that a run doesn't:
//
//   Power       meter rides only: average, normalised (Strava's weighted
//               average) and the variability index NP / avg, which says how
//               steady the ride was. 1.00–1.05 is a time trial or a trainer;
//               a group ride or a hilly loop runs well above that.
//   Efficiency  watts per heartbeat against the last six weeks of rides —
//               the same efficiency factor the page charts, so a caption
//               can't disagree with the trend it links to.
//   Intensity   the zone mix the last-ride card draws.
//   Week        rides, distance and moving time so far this week.
//   Longest     a flag when this was the longest ride in six weeks.
//
// Estimated watts never reach any of it: shape.js only keeps watts when
// device_watts was set, and every power line checks that again here.
//
// The fence, the lock and the write loop are shared — see caption.js.

import { mondayOf, toDayKey } from "./dates.js";
import { captionRecent, formAt, formLines, loadLine, previousOfKind, vsTypicalPct } from "./caption.js";
import { isRide, rideSeries, zoneMix } from "./cycling.js";
import { rideEfficiency } from "./efficiency.js";
import { median } from "./stats.js";

export const ATTRIBUTION = "Generated by https://maxeisen.me/cycling";
export const ATTRIBUTION_PLAIN = "Generated by the cycling dashboard";

// Fewer rides than this and "typical" or "longest" is describing a sample,
// not a habit.
const MIN_COMPARED = 3;
const COMPARE_DAYS = 42;

const finite = (value) => (Number.isFinite(Number(value)) && value !== null ? Number(value) : null);

function duration(sec) {
	const total = Math.round(Number(sec) || 0);
	const h = Math.floor(total / 3600);
	const m = Math.round((total % 3600) / 60);
	return h > 0 ? `${h}h ${String(m).padStart(2, "0")}m` : `${m}m`;
}

function powerLine(ride) {
	if (ride?.deviceWatts !== true) return null;
	const avg = finite(ride.averageWatts);
	if (!(avg > 0)) return null;
	const np = finite(ride.weightedAverageWatts);
	const parts = [`${Math.round(avg)} W avg`];
	if (np > 0) {
		parts.push(`${Math.round(np)} W NP`);
		parts.push(`VI ${(np / avg).toFixed(2)}`);
	}
	return `Power    ${parts.join("  ·  ")}`;
}

function efficiencyLine(ride, previous) {
	const ef = rideEfficiency(ride);
	if (!(ef > 0)) return null;
	const earlier = previous.map(rideEfficiency).filter((v) => v > 0);
	const typical = earlier.length >= MIN_COMPARED ? median(earlier) : null;
	const vs = typical > 0 ? `  ·  ${Math.round((ef / typical) * 100)}% of typical` : "";
	return `Efficiency  ${ef.toFixed(2)} W/bpm${vs}`;
}

function intensityLine(ride) {
	const mix = zoneMix(ride?.zoneSeconds);
	if (!mix) return null;
	const pct = (v) => `${Math.round(v)}%`;
	return `Intensity  ${pct(mix.easyPct)} easy  ·  ${pct(mix.moderatePct)} moderate  ·  ${pct(mix.hardPct)} hard`;
}

function weekLine(ride, rides) {
	const date = toDayKey(ride?.startDateLocal);
	if (!date) return null;
	const monday = mondayOf(date);
	const sofar = rides.filter((r) => {
		const day = toDayKey(r.startDateLocal);
		return day && mondayOf(day) === monday && String(r.startDateLocal) <= String(ride.startDateLocal);
	});
	if (!sofar.includes(ride)) sofar.push(ride);
	const km = sofar.reduce((sum, r) => sum + (Number(r.distanceM) || 0), 0) / 1000;
	const sec = sofar.reduce((sum, r) => sum + (Number(r.movingTimeSec) || 0), 0);
	const count = `${sofar.length} ride${sofar.length === 1 ? "" : "s"}`;
	return `Week     ${count}  ·  ${km.toFixed(0)} km  ·  ${duration(sec)}`;
}

function longestLine(ride, previous) {
	const distance = Number(ride?.distanceM) || 0;
	if (previous.length < MIN_COMPARED || !(distance > 0)) return null;
	const longest = Math.max(...previous.map((r) => Number(r.distanceM) || 0));
	return distance > longest ? `Longest ride in ${COMPARE_DAYS / 7} weeks` : null;
}

/**
 * The cycling caption's lines for one ride.
 *
 * @param {object} ride a stored, shaped ride.
 * @param {object} context
 * @param {object[]} context.rides every stored ride.
 * @param {object[]} context.series the ride-only fitness series.
 * @returns {string[]}
 */
export function rideCaptionLines(ride, { rides = [], series = [] } = {}) {
	const date = toDayKey(ride?.startDateLocal);
	const previous = previousOfKind(ride, rides, isRide, COMPARE_DAYS);
	const hasLoad = Number(ride?.load) > 0;

	// A ride with no heart rate has no load, so the only thing that moved the
	// series that day was a day's decay. Printing that under the ride would
	// read as the ride's doing.
	const lines = hasLoad ? formLines(formAt(series, date) || {}) : [];
	const typical = previous.filter((r) => Number(r.load) > 0).length >= MIN_COMPARED
		? vsTypicalPct(ride, rides, isRide)
		: null;
	for (const line of [
		loadLine(ride?.load, typical),
		powerLine(ride),
		efficiencyLine(ride, previous),
		intensityLine(ride),
	]) {
		if (line) lines.push(line);
	}

	// Week and longest are true of any ride. On their own they'd caption a
	// ride the page has nothing to say about, so they only follow a line that
	// came from the ride's own data.
	if (lines.length === 0) return [];
	for (const line of [weekLine(ride, rides), longestLine(ride, previous)]) {
		if (line) lines.push(line);
	}
	return lines;
}

/**
 * The cycling writer for captionRecent.
 *
 * @param {object} input
 * @param {object[]} input.records the merged index, any mix of sports.
 * @param {string} input.today day key.
 */
export function rideCaptionWriter({ records = [], today }) {
	const { rides, series } = rideSeries(records, today);
	return {
		sport: "ride",
		attribution: ATTRIBUTION,
		plainAttribution: ATTRIBUTION_PLAIN,
		isEligible: isRide,
		linesFor: (ride) => rideCaptionLines(ride, { rides, series }),
	};
}

/**
 * Caption recent rides that don't have a stamp yet.
 *
 * @param {object} input
 * @returns {Promise<{captioned: number, urlRejected: boolean}>}
 */
export function captionRecentRides({ records = [], today, ...io } = {}) {
	return captionRecent(rideCaptionWriter({ records, today }), { records, today, ...io });
}
