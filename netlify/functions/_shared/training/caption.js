// A short caption written back onto a Strava activity after a dashboard has
// numbers for it.
//
// The sync is otherwise read-only. This is the one write: append (or refresh)
// a fenced block at the end of the athlete's own description so the feed
// shows what the activity did to the numbers on the page. The fence is how a
// later pass finds the block and replaces it instead of stacking a second
// copy. Tagged `excuse:` / `note:` lines live above the fence and are left
// alone.
//
// This module is the part every sport shares: the fence, the attribution
// lock, the candidate window and the write-with-retry loop. What goes inside
// the block is a sport's business. A sport hands captionRecent a writer —
// see runCaption.js and rideCaption.js:
//
//   {
//     sport:            "run" | "ride", for logs
//     attribution:      line with the page's URL
//     plainAttribution: the same without a URL, for when Strava rejects one
//     isEligible(r):    whether a stored record is this writer's to caption
//     linesFor(r):      the caption's lines; [] leaves the record alone
//   }
//
// Attribution includes a URL because that's the point of the line. Strava has
// been known to 400 a description that looks like it contains a link; the
// loop retries once with the plain attribution rather than leaving the
// activity uncaptioned.

import { addDays, toDayKey } from "./dates.js";
import { median } from "./stats.js";

export const CAPTION_WINDOW_DAYS = 3;
// Per writer and per sync. Each caption is a read and a write.
export const CAPTION_BUDGET = 2;

const FENCE_START = "──";
const FENCE_END = "──";
// Optional " training" so a block written by the first version is still
// found and replaced rather than stacked under a second fence. Strava
// stores descriptions with CRLF; we normalise before matching.
const FENCE_RE = /\n*──(?: training)?\n[\s\S]*?\n──\s*$/;
// Every page name a caption has ever been attributed to, so a block written
// while the page was /training is still recognised as ours.
const ATTRIBUTION_RE =
	/Generated by (?:https:\/\/)?maxeisen\.me\/(?:running|training|cycling)|Generated by the (?:running|training|cycling) dashboard/;

function normalizeDescription(description) {
	return String(description || "").replace(/\r\n/g, "\n").replace(/\r/g, "\n");
}

const pad = (n) => String(n).padStart(2, "0");

/** A number with an explicit sign, or null when it isn't one. */
export function signed(value, digits = 1) {
	if (!Number.isFinite(value)) return null;
	const rounded = Number(value.toFixed(digits));
	const magnitude = Math.abs(rounded).toFixed(digits);
	if (rounded > 0) return `+${magnitude}`;
	return rounded < 0 ? `-${magnitude}` : magnitude;
}

/** h:mm:ss, or m:ss under an hour. */
export function clock(sec) {
	if (!(sec > 0)) return null;
	const total = Math.round(sec);
	const h = Math.floor(total / 3600);
	const m = Math.floor((total % 3600) / 60);
	const s = total % 60;
	return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${m}:${pad(s)}`;
}

/**
 * Fitness, fatigue and form on a day, and how far that day moved them.
 *
 * @param {{date: string, ctl: number, atl: number, tsb: number, load: number}[]} series
 * @param {string} date day key.
 * @returns {object|null} null without a day before it to compare against.
 */
export function formAt(series, date) {
	const idx = (series || []).findIndex((d) => d.date === date);
	if (idx < 1) return null;
	const before = series[idx - 1];
	const after = series[idx];
	return {
		ctl: after.ctl,
		ctlDelta: after.ctl - before.ctl,
		atl: after.atl,
		atlDelta: after.atl - before.atl,
		tsb: after.tsb,
		tsbDelta: after.tsb - before.tsb,
		dayLoad: after.load,
	};
}

/**
 * The records of the same kind in the window before (and including) a day,
 * other than the one being captioned.
 *
 * @param {object} record
 * @param {object[]} records
 * @param {(r: object) => boolean} isSameKind
 * @param {number} [days]
 * @returns {object[]}
 */
export function previousOfKind(record, records, isSameKind, days = 42) {
	const date = toDayKey(record?.startDateLocal);
	if (!date) return [];
	const from = addDays(date, -days);
	return (records || []).filter((other) => {
		if (other === record || String(other?.id) === String(record?.id)) return false;
		if (!isSameKind(other)) return false;
		const day = toDayKey(other?.startDateLocal);
		return day && day >= from && day <= date;
	});
}

/**
 * This record's load as a percentage of the median over the last six weeks
 * of the same kind.
 *
 * @returns {number|null}
 */
export function vsTypicalPct(record, records, isSameKind) {
	if (!(Number(record?.load) > 0)) return null;
	const previous = previousOfKind(record, records, isSameKind)
		.map((r) => Number(r.load))
		.filter((v) => v > 0);
	const typical = median(previous);
	return typical > 0 ? (Number(record.load) / typical) * 100 : null;
}

/**
 * Fitness / Fatigue / Form lines with the day's deltas. Shared by every
 * sport so the three read the same on a run as on a ride.
 *
 * @param {object} [form] from formAt().
 * @returns {string[]}
 */
export function formLines({ ctl, ctlDelta, atl, atlDelta, tsb, tsbDelta } = {}) {
	const lines = [];
	const fitnessDelta = signed(ctlDelta);
	const fatigueDelta = signed(atlDelta);
	const formDelta = signed(tsbDelta);
	if (fitnessDelta) {
		lines.push(`Fitness  ${fitnessDelta}${Number.isFinite(ctl) ? `  →  ${ctl.toFixed(1)}` : ""}`);
	}
	if (fatigueDelta) {
		lines.push(`Fatigue  ${fatigueDelta}${Number.isFinite(atl) ? `  →  ${atl.toFixed(1)}` : ""}`);
	}
	if (formDelta) {
		lines.push(`Form     ${formDelta}${Number.isFinite(tsb) ? `  →  ${tsb.toFixed(1)}` : ""}`);
	}
	return lines;
}

/**
 * The load line, with how it compares to typical when that's known.
 *
 * @param {number} load
 * @param {number|null} [typicalPct]
 * @returns {string|null}
 */
export function loadLine(load, typicalPct) {
	if (!Number.isFinite(load) || !(load > 0)) return null;
	const typical = Number.isFinite(typicalPct) ? `  ·  ${Math.round(typicalPct)}% of typical` : "";
	return `Load     ${Math.round(load)}${typical}`;
}

export function hasCaption(description) {
	return ATTRIBUTION_RE.test(normalizeDescription(description));
}

/**
 * Put the caption block at the end of a description, replacing a previous
 * copy of itself if one is already there.
 *
 * @param {string} description
 * @param {string[]} lines
 * @param {{attribution: string}} options
 * @returns {string}
 */
export function applyCaption(description, lines, { attribution }) {
	const block = [FENCE_START, ...(lines || []), attribution, FENCE_END].join("\n");
	const stripped = normalizeDescription(description).replace(FENCE_RE, "").trimEnd();
	return stripped ? `${stripped}\n\n${block}` : block;
}

// The writer's newest uncaptioned activities in the window, up to the budget.
function uncaptioned(writer, records, today) {
	const from = addDays(today, -CAPTION_WINDOW_DAYS);
	return (records || [])
		.filter((a) => {
			if (!a || a.captionedAt || !writer.isEligible(a)) return false;
			const day = toDayKey(a.startDateLocal);
			return day && day >= from;
		})
		.sort((a, b) => String(b.startDateLocal).localeCompare(String(a.startDateLocal)))
		.slice(0, CAPTION_BUDGET);
}

/**
 * One PUT, and one retry without the URL if Strava rejects the first.
 *
 * @returns {Promise<{written: boolean, urlRejected: boolean, stop: boolean}>}
 */
async function writeCaption(writer, record, description, lines, putDescription) {
	try {
		await putDescription(record.id, applyCaption(description, lines, { attribution: writer.attribution }));
		return { written: true, urlRejected: false, stop: false };
	} catch (err) {
		if (err?.status === 429) return { written: false, urlRejected: false, stop: true };
		if (err?.status !== 400) {
			console.error(`Failed to caption ${writer.sport} ${record.id}`, err);
			return { written: false, urlRejected: false, stop: false };
		}
	}
	try {
		await putDescription(record.id, applyCaption(description, lines, { attribution: writer.plainAttribution }));
		return { written: true, urlRejected: true, stop: false };
	} catch (err) {
		console.error(`Failed to caption ${writer.sport} ${record.id} without URL`, err);
		return { written: false, urlRejected: true, stop: err?.status === 429 };
	}
}

/**
 * Caption the writer's recent activities that don't have a stamp yet.
 *
 * Mutates records in place (`captionedAt`). One PUT per activity, and a retry
 * without the URL if Strava rejects the description.
 *
 * @param {object} writer see the top of this file.
 * @param {object} input
 * @param {object[]} input.records the merged index.
 * @param {string} input.today day key.
 * @param {(id: string|number) => Promise<string>} input.getDescription
 * @param {(id: string|number, description: string) => Promise<void>} input.putDescription
 * @param {number} [input.deadline] epoch ms.
 * @returns {Promise<{captioned: number, urlRejected: boolean}>}
 */
export async function captionRecent(
	writer,
	{ records = [], today, getDescription, putDescription, deadline = Infinity } = {},
) {
	const candidates = uncaptioned(writer, records, today);
	let captioned = 0;
	let urlRejected = false;
	const stamp = (record) => {
		record.captionedAt = new Date().toISOString();
		captioned += 1;
	};

	for (const record of candidates) {
		if (Date.now() > deadline) break;
		const lines = writer.linesFor(record);
		if (!lines || lines.length === 0) continue;

		let description;
		try {
			description = await getDescription(record.id);
		} catch (err) {
			if (err?.status === 429) break;
			console.error(`Failed to read description on ${writer.sport} ${record.id}`, err);
			continue;
		}

		if (typeof description !== "string") description = "";
		// The attribution line is the lock. If it's already on the activity,
		// a later pass must not write another copy — even when the blob stamp
		// was lost, the fence changed, or Strava stored CRLF.
		if (hasCaption(description)) {
			stamp(record);
			continue;
		}

		const outcome = await writeCaption(writer, record, description, lines, putDescription);
		if (outcome.urlRejected) urlRejected = true;
		if (outcome.written) stamp(record);
		if (outcome.stop) break;
	}

	return { captioned, urlRejected };
}
