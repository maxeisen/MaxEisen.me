// A short caption written back onto a Strava activity after a dashboard has
// numbers for it.
//
// The sync is otherwise read-only. This is the one write: append (or refresh)
// a fenced block at the end of the athlete's own description so the feed
// shows what the activity did to the numbers on the page. The fence is how a
// later pass finds the block and replaces it instead of stacking a second
// copy. Tagged `excuse:` / `note:` lines live above the fence and are left
// alone.
//
// This module is the part every sport shares: the fence, the attribution
// lock, the candidate window and the write-with-retry loop. What goes inside
// the block is a sport's business. A sport hands captionRecent a writer —
// see runCaption.js and rideCaption.js:
//
//   {
//     sport:            "run" | "ride", for logs
//     attribution:      line with the page's URL
//     plainAttribution: the same without a URL, for when Strava rejects one
//     isEligible(r):    whether a stored record is this writer's to caption
//     linesFor(r, d):   the caption's lines; [] leaves the record alone. `d`
//                       is the detailed activity read from Strava, or
//                       undefined for the cheap check before that read.
//     titleFor(r, d):   optional. A new title for the activity, or null to
//                       leave the title alone.
//     version:          optional, default 1. Stamped on each record captioned
//                       as `captionVersion`.
//     refreshLast:      optional, default 0. Raising `version` rewrites the
//                       caption on this many of the most recent activities
//                       once, if theirs was written by an older version. This
//                       is how a change to the caption reaches the last few
//                       activities on deploy rather than only new ones.
//   }
//
// Attribution includes a URL because that's the point of the line. Strava has
// been known to 400 a description that looks like it contains a link; the
// loop retries once with the plain attribution rather than leaving the
// activity uncaptioned.

import { addDays, mondayOf, toDayKey } from "./dates.js";
import { median } from "./stats.js";
import { zoneMix } from "./zones.js";

export const CAPTION_WINDOW_DAYS = 3;
// How far back "typical" and "longest" look, and how many activities that
// window needs before either means a habit rather than a sample.
export const COMPARE_DAYS = 42;
export const MIN_COMPARED = 3;
// Per writer and per sync. Each caption is a read and a write.
export const CAPTION_BUDGET = 2;

const FENCE_START = "──";
const FENCE_END = "──";
// Optional " training" so a block written by the first version is still
// found and replaced rather than stacked under a second fence. Strava
// stores descriptions with CRLF; we normalise before matching.
const FENCE_RE = /\n*──(?: training)?\n[\s\S]*?\n──\s*$/;
// Every page name a caption has ever been attributed to, so a block written
// while the page was /training is still recognised as ours.
const ATTRIBUTION_RE =
	/Generated by (?:https:\/\/)?maxeisen\.me\/(?:running|training|cycling)|Generated by the (?:running|training|cycling) dashboard/;

function normalizeDescription(description) {
	return String(description || "").replace(/\r\n/g, "\n").replace(/\r/g, "\n");
}

const pad = (n) => String(n).padStart(2, "0");

/** A number with an explicit sign, or null when it isn't one. */
export function signed(value, digits = 1) {
	if (!Number.isFinite(value)) return null;
	const rounded = Number(value.toFixed(digits));
	const magnitude = Math.abs(rounded).toFixed(digits);
	if (rounded > 0) return `+${magnitude}`;
	return rounded < 0 ? `-${magnitude}` : magnitude;
}

/** h:mm:ss, or m:ss under an hour. */
export function clock(sec) {
	if (!(sec > 0)) return null;
	const total = Math.round(sec);
	const h = Math.floor(total / 3600);
	const m = Math.floor((total % 3600) / 60);
	const s = total % 60;
	return h > 0 ? `${h}:${pad(m)}:${pad(s)}` : `${m}:${pad(s)}`;
}

/**
 * Fitness, fatigue and form on a day, and how far that day moved them.
 *
 * @param {{date: string, ctl: number, atl: number, tsb: number, load: number}[]} series
 * @param {string} date day key.
 * @returns {object|null} null without a day before it to compare against.
 */
export function formAt(series, date) {
	const idx = (series || []).findIndex((d) => d.date === date);
	if (idx < 1) return null;
	const before = series[idx - 1];
	const after = series[idx];
	return {
		ctl: after.ctl,
		ctlDelta: after.ctl - before.ctl,
		atl: after.atl,
		atlDelta: after.atl - before.atl,
		tsb: after.tsb,
		tsbDelta: after.tsb - before.tsb,
		dayLoad: after.load,
	};
}

/**
 * The records of the same kind in the window before (and including) a day,
 * other than the one being captioned.
 *
 * @param {object} record
 * @param {object[]} records
 * @param {(r: object) => boolean} isSameKind
 * @param {number} [days]
 * @returns {object[]}
 */
export function previousOfKind(record, records, isSameKind, days = COMPARE_DAYS) {
	const date = toDayKey(record?.startDateLocal);
	if (!date) return [];
	const from = addDays(date, -days);
	return (records || []).filter((other) => {
		if (other === record || String(other?.id) === String(record?.id)) return false;
		if (!isSameKind(other)) return false;
		const day = toDayKey(other?.startDateLocal);
		return day && day >= from && day <= date;
	});
}

/**
 * This record's load as a percentage of the median over the last six weeks
 * of the same kind. Null on fewer than MIN_COMPARED earlier loads.
 *
 * @returns {number|null}
 */
export function vsTypicalPct(record, records, isSameKind) {
	const earlier = previousOfKind(record, records, isSameKind).map((r) => Number(r.load));
	return pctOfTypical(Number(record?.load), earlier);
}

/**
 * Fitness / Fatigue / Form lines with the day's deltas. Shared by every
 * sport so the three read the same on a run as on a ride.
 *
 * @param {object} [form] from formAt().
 * @returns {string[]}
 */
export function formLines({ ctl, ctlDelta, atl, atlDelta, tsb, tsbDelta } = {}) {
	const lines = [];
	const fitnessDelta = signed(ctlDelta);
	const fatigueDelta = signed(atlDelta);
	const formDelta = signed(tsbDelta);
	if (fitnessDelta) {
		lines.push(`Fitness  ${fitnessDelta}${Number.isFinite(ctl) ? `  →  ${ctl.toFixed(1)}` : ""}`);
	}
	if (fatigueDelta) {
		lines.push(`Fatigue  ${fatigueDelta}${Number.isFinite(atl) ? `  →  ${atl.toFixed(1)}` : ""}`);
	}
	if (formDelta) {
		lines.push(`Form     ${formDelta}${Number.isFinite(tsb) ? `  →  ${tsb.toFixed(1)}` : ""}`);
	}
	return lines;
}

/**
 * The load line, with how it compares to typical when that's known.
 *
 * @param {number} load
 * @param {number|null} [typicalPct]
 * @returns {string|null}
 */
export function loadLine(load, typicalPct) {
	if (!Number.isFinite(load) || !(load > 0)) return null;
	const typical = Number.isFinite(typicalPct) ? `  ·  ${Math.round(typicalPct)}% of typical` : "";
	return `Load     ${Math.round(load)}${typical}`;
}

/** 2h 05m, or 45m under an hour. */
export function duration(sec) {
	const total = Math.round(Number(sec) || 0);
	const h = Math.floor(total / 3600);
	const m = Math.round((total % 3600) / 60);
	return h > 0 ? `${h}h ${String(m).padStart(2, "0")}m` : `${m}m`;
}

/**
 * A value as a percentage of the median of earlier ones, once there are
 * enough of them.
 *
 * @param {number} value
 * @param {number[]} earlier
 * @returns {number|null}
 */
export function pctOfTypical(value, earlier) {
	const usable = (earlier || []).filter((v) => v > 0);
	if (!(value > 0) || usable.length < MIN_COMPARED) return null;
	const typical = median(usable);
	return typical > 0 ? (value / typical) * 100 : null;
}

/**
 * Efficiency factor, against the same measure on earlier activities. What
 * the factor is (watts or speed per beat) is the sport's business.
 *
 * @param {number|null} value
 * @param {number[]} earlier
 * @param {string} unit
 * @returns {string|null}
 */
export function efficiencyLine(value, earlier, unit) {
	if (!(value > 0)) return null;
	const pct = pctOfTypical(value, earlier);
	const vs = pct !== null ? `  ·  ${Math.round(pct)}% of typical` : "";
	return `Efficiency  ${value.toFixed(2)} ${unit}${vs}`;
}

/** The zone mix the last-activity card draws, as one line. */
export function intensityLine(zoneSeconds) {
	const mix = zoneMix(zoneSeconds);
	if (!mix) return null;
	const pct = (v) => `${Math.round(v)}%`;
	return `Intensity  ${pct(mix.easyPct)} easy  ·  ${pct(mix.moderatePct)} moderate  ·  ${pct(mix.hardPct)} hard`;
}

/**
 * Count, distance and moving time so far this week (Monday start), up to and
 * including this activity — and against the plan's kilometres when there are
 * some.
 *
 * @param {object} record
 * @param {object[]} sameKind every stored activity of the record's sport.
 * @param {string} noun "run" or "ride".
 * @param {{plannedKm?: number|null}} [options]
 * @returns {string|null}
 */
export function weekLine(record, sameKind, noun, { plannedKm = null } = {}) {
	const date = toDayKey(record?.startDateLocal);
	if (!date) return null;
	const monday = mondayOf(date);
	const sofar = (sameKind || []).filter((r) => {
		const day = toDayKey(r.startDateLocal);
		return day && mondayOf(day) === monday && String(r.startDateLocal) <= String(record.startDateLocal);
	});
	if (!sofar.includes(record)) sofar.push(record);
	const km = sofar.reduce((sum, r) => sum + (Number(r.distanceM) || 0), 0) / 1000;
	const sec = sofar.reduce((sum, r) => sum + (Number(r.movingTimeSec) || 0), 0);
	const count = `${sofar.length} ${noun}${sofar.length === 1 ? "" : "s"}`;
	const distance = plannedKm > 0 ? `${km.toFixed(0)} of ${Math.round(plannedKm)} km` : `${km.toFixed(0)} km`;
	return `Week     ${count}  ·  ${distance}  ·  ${duration(sec)}`;
}

/**
 * A flag when this was the longest of its kind in the comparison window.
 *
 * @param {object} record
 * @param {object[]} previous from previousOfKind().
 * @param {string} noun
 * @returns {string|null}
 */
export function longestLine(record, previous, noun) {
	const distance = Number(record?.distanceM) || 0;
	if ((previous || []).length < MIN_COMPARED || !(distance > 0)) return null;
	const longest = Math.max(...previous.map((r) => Number(r.distanceM) || 0));
	return distance > longest ? `Longest ${noun} in ${COMPARE_DAYS / 7} weeks` : null;
}

export function hasCaption(description) {
	return ATTRIBUTION_RE.test(normalizeDescription(description));
}

/**
 * Put the caption block at the end of a description, replacing a previous
 * copy of itself if one is already there.
 *
 * @param {string} description
 * @param {string[]} lines
 * @param {{attribution: string}} options
 * @returns {string}
 */
export function applyCaption(description, lines, { attribution }) {
	const block = [FENCE_START, ...(lines || []), attribution, FENCE_END].join("\n");
	const stripped = normalizeDescription(description).replace(FENCE_RE, "").trimEnd();
	return stripped ? `${stripped}\n\n${block}` : block;
}

const newestFirst = (a, b) => String(b.startDateLocal).localeCompare(String(a.startDateLocal));

/**
 * What this pass should caption, up to the budget: the writer's newest
 * uncaptioned activities in the window first, then any of its most recent
 * activities whose caption an older version wrote.
 *
 * @returns {{record: object, refresh: boolean}[]}
 */
function captionTargets(writer, records, today) {
	const from = addDays(today, -CAPTION_WINDOW_DAYS);
	const eligible = (records || []).filter((a) => a && writer.isEligible(a)).sort(newestFirst);
	const fresh = eligible
		.filter((a) => {
			if (a.captionedAt) return false;
			const day = toDayKey(a.startDateLocal);
			return day && day >= from;
		})
		.map((record) => ({ record, refresh: false }));
	const version = writer.version || 1;
	const stale = eligible
		.slice(0, writer.refreshLast || 0)
		.filter((a) => a.captionedAt && (Number(a.captionVersion) || 1) < version)
		.map((record) => ({ record, refresh: true }));
	return [...fresh, ...stale].slice(0, CAPTION_BUDGET);
}

/**
 * One PUT, and one retry without the URL if Strava rejects the first. The
 * title, when there is one, goes in the same PUT.
 *
 * @returns {Promise<{written: boolean, urlRejected: boolean, stop: boolean}>}
 */
async function writeCaption(writer, record, description, lines, title, putActivity) {
	const fields = (attribution) => ({
		description: applyCaption(description, lines, { attribution }),
		...(title ? { name: title } : {}),
	});
	try {
		await putActivity(record.id, fields(writer.attribution));
		return { written: true, urlRejected: false, stop: false };
	} catch (err) {
		if (err?.status === 429) return { written: false, urlRejected: false, stop: true };
		if (err?.status !== 400) {
			console.error(`Failed to caption ${writer.sport} ${record.id}`, err);
			return { written: false, urlRejected: false, stop: false };
		}
	}
	try {
		await putActivity(record.id, fields(writer.plainAttribution));
		return { written: true, urlRejected: true, stop: false };
	} catch (err) {
		console.error(`Failed to caption ${writer.sport} ${record.id} without URL`, err);
		return { written: false, urlRejected: true, stop: err?.status === 429 };
	}
}

/**
 * Caption the writer's recent activities that don't have a stamp yet.
 *
 * Mutates records in place (`captionedAt`, `captionVersion`, and `name` and
 * `titledAs` when the title changed).
 * One PUT per activity, and a retry without the URL if Strava rejects the
 * description.
 *
 * @param {object} writer see the top of this file.
 * @param {object} input
 * @param {object[]} input.records the merged index.
 * @param {string} input.today day key.
 * @param {(id: string|number) => Promise<object>} input.getActivity the
 *   detailed activity: description, name, laps.
 * @param {(id: string|number, fields: {description: string, name?: string}) => Promise<void>} input.putActivity
 * @param {number} [input.deadline] epoch ms.
 * @returns {Promise<{captioned: number, urlRejected: boolean}>}
 */
export async function captionRecent(
	writer,
	{ records = [], today, getActivity, putActivity, deadline = Infinity } = {},
) {
	const targets = captionTargets(writer, records, today);
	let captioned = 0;
	let urlRejected = false;
	const stamp = (record) => {
		record.captionedAt = new Date().toISOString();
		record.captionVersion = writer.version || 1;
		captioned += 1;
	};

	for (const { record, refresh } of targets) {
		if (Date.now() > deadline) break;
		const preview = writer.linesFor(record);
		if (!preview || preview.length === 0) continue;

		let detail;
		try {
			detail = (await getActivity(record.id)) || {};
		} catch (err) {
			if (err?.status === 429) break;
			console.error(`Failed to read ${writer.sport} ${record.id}`, err);
			continue;
		}

		const description = typeof detail.description === "string" ? detail.description : "";
		// The attribution line is the lock. If it's already on the activity,
		// a later pass must not write another copy — even when the blob stamp
		// was lost, the fence changed, or Strava stored CRLF.
		//
		// A refresh is the one pass that writes over it, and only when the
		// whole fenced block is there to replace: applyCaption swaps that block
		// in place, so the athlete's own text above it is kept. A caption the
		// athlete deleted, or a block that's no longer intact, is left alone.
		const replaceable = refresh && hasCaption(description) && FENCE_RE.test(normalizeDescription(description));
		if (refresh ? !replaceable : hasCaption(description)) {
			stamp(record);
			continue;
		}

		const lines = writer.linesFor(record, detail);
		const title = writer.titleFor?.(record, detail) ?? null;
		const outcome = await writeCaption(writer, record, description, lines, title, putActivity);
		if (outcome.urlRejected) urlRejected = true;
		if (outcome.written) {
			stamp(record);
			if (title) {
				record.name = title;
				// So the next version can tell its own title from the athlete's.
				record.titledAs = title;
			}
		}
		if (outcome.stop) break;
	}

	return { captioned, urlRejected };
}
