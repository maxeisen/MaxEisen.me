// The running caption. It opens with a sentence or two on what kind of run
// it was, against the planned session when there is one (see
// runDescription.js), and a run still carrying Strava's default title gets a
// short one naming the workout. The lines shared with rides — fitness, fatigue and
// form, load against typical, efficiency, intensity, the week and a
// longest-in-six-weeks flag — read exactly as a ride's do. Around them, what
// only a run has:
//
//   Pace        moving pace, and grade-adjusted pace when the hills moved it.
//   Efficiency  speed per heartbeat (grade-adjusted), against the last six
//               weeks of aerobic runs — the same series the page charts, with
//               the same exclusion: a hard run's number moves with its
//               intensity, so it gets no line rather than a misleading one.
//   Decoupling  how far pace per beat drifted between the halves, on runs of
//               an hour or more, which is where it means anything.
//   Week        against the plan's kilometres when the week has a target.
//   Projected   the marathon projection, and how far this run moved it.
//
// The fence, the lock and the write loop are shared — see caption.js.

import { mondayOf, toDayKey } from "./dates.js";
import { activityEfficiency } from "./efficiency.js";
import { projectMarathon, sessionProjectionDelta } from "./marathonProjection.js";
import { matchRunsToPlan, plannedKm, plannedWeek } from "./plan.js";
import { describeRun, retitle, shapeLaps } from "./runDescription.js";
import { isRunActivity } from "./shape.js";
import { hrZoneFloors } from "./zones.js";
import {
	captionRecent,
	clock,
	efficiencyLine,
	formAt,
	formLines,
	intensityLine,
	loadLine,
	longestLine,
	previousOfKind,
	vsTypicalPct,
	weekLine,
} from "./caption.js";

export const ATTRIBUTION = "Generated by https://maxeisen.me/running";
export const ATTRIBUTION_PLAIN = "Generated by the running dashboard";

// Below this decoupling is mostly warm-up, not endurance.
const DECOUPLING_MIN_SEC = 60 * 60;
// The usual marker for being aerobically ready for the distance.
const DECOUPLING_STEADY_PCT = 5;
// A GAP within this of the flat pace is rounding, not hills.
const GAP_MIN_DIFF_SEC = 3;

const pace = (secPerKm) => (secPerKm > 0 ? `${clock(secPerKm)}/km` : null);

/**
 * Seconds today's (or this day's) efforts moved the headline prediction.
 *
 * Zero when the day's running did not change the shared estimate. Null when
 * there is no prediction at all.
 *
 * @param {object[]} efforts from collectBestEfforts().
 * @param {string} date day key of the run being captioned.
 * @param {number} targetDistanceM
 * @param {object[]} [runs] shaped runs, so training support can move.
 * @returns {number|null}
 */
export function sessionDeltaSec(efforts, date, targetDistanceM, runs = []) {
	return sessionProjectionDelta({
		runs,
		efforts,
		today: date,
		date,
		targetDistanceM,
	})?.sessionDeltaSec ?? null;
}

/**
 * Form, load, any run detail lines, then the projection.
 *
 * @param {object} metrics
 * @param {string[]} [metrics.details] from runDetailLines().
 * @returns {string[]}
 */
export function formatCaptionLines({
	load,
	vsTypicalPct: typicalPct,
	predictedSec,
	sessionDeltaSec: delta,
	details = [],
	...form
} = {}) {
	const lines = formLines(form);
	const loaded = loadLine(load, typicalPct);
	if (loaded) lines.push(loaded);
	lines.push(...details.filter(Boolean));

	const finish = clock(predictedSec);
	if (finish) {
		let move = "no change";
		if (Number.isFinite(delta) && delta !== 0) {
			const faster = delta < 0;
			move = `${clock(Math.abs(delta))} ${faster ? "faster" : "slower"}`;
		}
		lines.push(`Projected  ${finish}  ·  ${move}`);
	}
	return lines;
}

function paceLine(run) {
	const flat = pace(Number(run?.paceSecPerKm));
	if (!flat) return null;
	const gapSec = Number(run?.gapPaceSecPerKm);
	const hilly = gapSec > 0 && Math.abs(gapSec - Number(run.paceSecPerKm)) >= GAP_MIN_DIFF_SEC;
	return `Pace     ${flat}${hilly ? `  ·  GAP ${pace(gapSec)}` : ""}`;
}

function runEfficiencyLine(run, previous, ceilingHr) {
	const aerobic = (r) => !(ceilingHr > 0) || Number(r?.averageHr) < ceilingHr;
	if (!aerobic(run)) return null;
	const earlier = previous.filter(aerobic).map(activityEfficiency);
	return efficiencyLine(activityEfficiency(run), earlier, "m/min/bpm");
}

function decouplingLine(run) {
	const pct = Number(run?.decouplingPct);
	if (run?.decouplingPct == null || !Number.isFinite(pct)) return null;
	if (!(Number(run.movingTimeSec) >= DECOUPLING_MIN_SEC)) return null;
	const steady = pct < DECOUPLING_STEADY_PCT ? `  ·  under ${DECOUPLING_STEADY_PCT}%` : "";
	return `Decoupling  ${pct.toFixed(1)}%${steady}`;
}

/**
 * The lines a run has between its load and its projection.
 *
 * @param {object} run a stored, shaped run.
 * @param {object} context
 * @param {object[]} context.runs every stored run, oldest first.
 * @param {object} [context.plan]
 * @returns {string[]}
 */
export function runDetailLines(run, { runs = [], plan = null } = {}) {
	const previous = previousOfKind(run, runs, isRunActivity);
	const ceilingHr = hrZoneFloors(plan?.thresholds || {})?.[3] ?? null;
	const date = toDayKey(run?.startDateLocal);
	const week = date ? plannedWeek(plan, mondayOf(date)) : null;
	return [
		paceLine(run),
		runEfficiencyLine(run, previous, ceilingHr),
		decouplingLine(run),
		intensityLine(run?.zoneSeconds),
		weekLine(run, runs, "run", { plannedKm: week ? plannedKm(week) : null }),
		longestLine(run, previous, "run"),
	].filter(Boolean);
}

/**
 * The running writer for captionRecent.
 *
 * @param {object} input
 * @param {object[]} input.records the merged index.
 * @param {object[]} input.series the block's fitness series.
 * @param {object[]} input.efforts from collectBestEfforts().
 * @param {object[]} [input.runs] shaped runs; derived from records when empty.
 * @param {object} [input.plan] for zones, the week's target and the session.
 * @param {number} [input.raceDistanceM]
 */
export function runCaptionWriter({
	records = [],
	series = [],
	efforts = [],
	runs = [],
	plan = null,
	raceDistanceM = 42195,
}) {
	const allRuns = [...(runs.length ? runs : records.filter(isRunActivity))].sort((a, b) =>
		String(a.startDateLocal).localeCompare(String(b.startDateLocal)),
	);
	const matches = plan ? matchRunsToPlan(allRuns, plan) : [];
	const matchFor = (run) => matches[allRuns.findIndex((r) => String(r.id) === String(run.id))] ?? null;
	return {
		sport: "run",
		attribution: ATTRIBUTION,
		plainAttribution: ATTRIBUTION_PLAIN,
		isEligible: isRunActivity,
		// Raising this rewrites the last five runs' captions once.
		// 2: the caption opens with what kind of run it was, and a default
		//    title is replaced.
		// 3: walking rests count as rest, so a session with walks between
		//    reps reads as its reps; reps split by a longer rest read as sets.
		// 4: reps are counted from the pace trace when the laps are plain
		//    1 km auto-laps.
		// 5: jogged rests count as rest, so the warm-up and cool-down are no
		//    longer read as reps.
		version: 5,
		refreshLast: 5,
		titleFor(record, detail) {
			const { title, planName } = describeRun(record, {
				match: matchFor(record),
				laps: shapeLaps(detail?.laps),
				runs: allRuns,
			});
			return retitle(detail?.name ?? record.name, title, [record.titledAs, planName].filter(Boolean));
		},
		linesFor(record, detail) {
			const { summary } = describeRun(record, { match: matchFor(record), laps: shapeLaps(detail?.laps), runs: allRuns });
			const date = toDayKey(record.startDateLocal);
			const form = formAt(series, date);
			const predicted = projectMarathon({
				runs: allRuns,
				efforts,
				today: date,
				targetDistanceM: raceDistanceM,
				tsb: form?.tsb ?? null,
			});
			const lines = formatCaptionLines({
				...form,
				load: record.load,
				vsTypicalPct: vsTypicalPct(record, records, isRunActivity),
				details: runDetailLines(record, { runs: allRuns, plan }),
				predictedSec: predicted?.predictedSec ?? null,
				sessionDeltaSec: sessionDeltaSec(efforts, date, raceDistanceM, allRuns),
			});
			// A blank line keeps the sentence apart from the figures under it.
			return summary ? [summary, "", ...lines] : lines;
		},
	};
}

/**
 * Caption recent runs that don't have a stamp yet.
 *
 * @param {object} input the writer's inputs plus captionRecent's.
 * @returns {Promise<{captioned: number, urlRejected: boolean}>}
 */
export function captionRecentRuns({ records = [], series, efforts, runs, plan, raceDistanceM, ...io } = {}) {
	return captionRecent(runCaptionWriter({ records, series, efforts, runs, plan, raceDistanceM }), {
		records,
		...io,
	});
}
